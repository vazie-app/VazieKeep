"""Generate the synthetic, feature-rich KDBX 4 vaults in shared/test-vectors/editable.

They exercise the writer: attachments, entry history, a recycle bin, tags, protected and plain
custom fields, Unicode, custom data the app doesn't model, KDBX 4.0 and 4.1, gzip and no
compression. Every value is invented test data. Run with the same venv as generate_kdbx4.py:

    .venv/bin/python tooling/test-vectors/generate_editable.py
"""

import hashlib
import json
import os
import sys
from pathlib import Path

from lxml import etree
from pykeepass import create_database

sys.path.insert(0, str(Path(__file__).resolve().parent))
from generate_kdbx4 import PASSWORD, kdf_parameters  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "shared" / "test-vectors" / "editable"
ATTACHMENT = b"synthetic attachment \x00\x01\x02 bytes " * 40


def populate(kp, *, recycle_bin):
    kp.database_name = "Editable Fixture"
    kp.database_description = "Generated by tooling/test-vectors/generate_editable.py"
    root = kp.root_group
    web = kp.add_group(root, "Web")
    work = kp.add_group(web, "Work")
    kp.add_group(root, "Empty Group")
    archive = kp.add_group(root, "Archive")

    mail = kp.add_entry(web, "Example Mail", "alice@example.org", "hunter2-synthetic", url="https://mail.example.org/login", tags=["mail", "personal"], force_creation=True)
    mail.set_custom_property("Recovery Code", "RC-0000-1111", protect=True)
    mail.set_custom_property("Plain Note", "not secret", protect=False)

    bank = kp.add_entry(work, "Bank", "bob", "first-password", url="https://bank.example.com", notes="Line one\nLine two", force_creation=True)
    bank.save_history()
    bank.password = "second-password"
    bank.save_history()
    bank.password = "third-password"

    files = kp.add_entry(work, "With Attachment", "carol", "attachment-pass", force_creation=True)
    binary_id = kp.add_binary(ATTACHMENT, protected=True)
    files.add_attachment(binary_id, "notes.bin")

    kp.add_entry(archive, "Юникод 🗝️ 名前", "пользователь", "пароль-🔑", url="https://пример.испытание", notes="日本語", force_creation=True)
    old = kp.add_entry(root, "Old Account", "dave", "old-pass", force_creation=True)
    if recycle_bin:
        kp.trash_entry(old)

    # Elements the app doesn't model, to prove they survive a save.
    meta = kp.tree.find("Meta")
    meta.find("RecycleBinEnabled").text = "True" if recycle_bin else "False"
    custom = meta.find("CustomData")
    if custom is None:
        custom = etree.SubElement(meta, "CustomData")
    item = etree.SubElement(custom, "Item")
    etree.SubElement(item, "Key").text = "VazieKeepFixture"
    etree.SubElement(item, "Value").text = "preserve-me"
    entry_custom = etree.SubElement(mail._element, "CustomData")
    entry_item = etree.SubElement(entry_custom, "Item")
    etree.SubElement(entry_item, "Key").text = "browser.extension"
    etree.SubElement(entry_item, "Value").text = "keep-this-too"


def build(name, *, cipher, kdf, minor, compression, recycle_bin=True):
    path = OUT / f"{name}.kdbx"
    kp = create_database(str(path), password=PASSWORD)
    header = kp.kdbx.header.value
    header.minor_version = minor
    header.dynamic_header.cipher_id.data = cipher
    header.dynamic_header.encryption_iv.data = os.urandom(12 if cipher == "chacha20" else 16)
    header.dynamic_header.kdf_parameters.data = kdf_parameters(kdf)
    header.dynamic_header.compression_flags.data.compression = compression
    populate(kp, recycle_bin=recycle_bin)
    kp.save()
    return path


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.kdbx"):
        old.unlink()
    build("rich-aes-argon2d-gzip", cipher="aes256", kdf="argon2d", minor=0, compression=True)
    build("rich-chacha-aeskdf-plain-41", cipher="chacha20", kdf="aes-kdf", minor=1, compression=False)
    build("rich-no-recycle-bin", cipher="aes256", kdf="argon2id", minor=0, compression=True, recycle_bin=False)
    checksums = {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(OUT.glob("*.kdbx"))}
    (OUT / "SHA256SUMS").write_text("".join(f"{h}  {n}\n" for n, h in checksums.items()))
    print(json.dumps(checksums, indent=2))


if __name__ == "__main__":
    main()
