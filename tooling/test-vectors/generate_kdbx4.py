def populate_minimal(kp):
    kp.database_name = "Minimal"
    kp.add_entry(kp.root_group, "Only Entry", "user", PASSWORD + "!", force_creation=True)


def populate_marker(kp):
    kp.database_name = "Leak Marker"
    entry = kp.add_entry(kp.root_group, "Marker Entry", "marker-user", LEAK_MARKER, url="https://marker.example.org", force_creation=True)
    entry.set_custom_property("Marker Field", LEAK_MARKER, protect=True)


def build(name, *, cipher, kdf, password=PASSWORD, minor=0, full=True, populate=None):
    path = OUT / f"{name}.kdbx"
    kp = create_database(str(path), password=password)
    header = kp.kdbx.header.value
    header.minor_version = minor
    header.dynamic_header.cipher_id.data = cipher
    header.dynamic_header.encryption_iv.data = os.urandom(12 if cipher == "chacha20" else 16)
    header.dynamic_header.kdf_parameters.data = kdf_parameters(kdf)
    (populate or (populate_full if full else populate_minimal))(kp)
    kp.save()
    return path


def flip(data, offset):
    patched = bytearray(data)
    patched[offset] ^= 0x01
    return bytes(patched)


def header_end(data):
    offset = 12
    while True:
        field_id = data[offset]
        (size,) = struct.unpack_from("<I", data, offset + 1)
        offset += 5 + size
        if field_id == 0:
            return offset


def derive_negative(source, name, transform):
    path = OUT / f"{name}.kdbx"
    path.write_bytes(transform(source.read_bytes()))
    return path


def build_marker():
    build("leak-marker", cipher="chacha20", kdf="argon2id", password=LEAK_MARKER, populate=populate_marker)


def write_checksums():
    checksums = {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(OUT.glob("*.kdbx"))}
    (OUT / "SHA256SUMS").write_text("".join(f"{h}  {n}\n" for n, h in checksums.items()))
    return checksums


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    if sys.argv[1:] == ["--only", "leak-marker"]:
        build_marker()
        print(json.dumps(write_checksums(), indent=2))
        return
    for old in OUT.glob("*.kdbx"):
        old.unlink()

    aes_argon2d = build("aes256-argon2d", cipher="aes256", kdf="argon2d")
    build("aes256-aeskdf", cipher="aes256", kdf="aes-kdf")
    build("chacha20-argon2id", cipher="chacha20", kdf="argon2id")
    build("chacha20-aeskdf-kdbx41", cipher="chacha20", kdf="aes-kdf", minor=1, full=False)
    build("unicode-password", cipher="aes256", kdf="argon2id", password=UNICODE_PASSWORD, full=False)

    end = header_end(aes_argon2d.read_bytes())
    derive_negative(aes_argon2d, "corrupted-payload", lambda d: flip(d, end + 64 + 32 + 4 + 40))
    derive_negative(aes_argon2d, "invalid-header-hmac", lambda d: flip(d, end + 32 + 5))
    derive_negative(aes_argon2d, "tampered-header", lambda d: flip(d, 12 + 5 + 16 + 5 + 4 + 5 + 3))
    derive_negative(aes_argon2d, "unsupported-version-3.1", lambda d: d[:8] + b"\x01\x00\x03\x00" + d[12:])
    derive_negative(aes_argon2d, "unsupported-version-5.0", lambda d: d[:8] + b"\x00\x00\x05\x00" + d[12:])
    derive_negative(aes_argon2d, "truncated", lambda d: d[: end + 80])
    build_marker()

    print(json.dumps(write_checksums(), indent=2))


if __name__ == "__main__":
    main()
