"""Generate the synthetic KDBX 4 vaults in shared/test-vectors/kdbx4.

Every password, name and value below is invented test data. Nothing here is
anyone's real vault. Run:

    python3 -m venv .venv && .venv/bin/pip install -r tooling/test-vectors/requirements.txt
    .venv/bin/python tooling/test-vectors/generate_kdbx4.py

The vaults are written by pykeepass (an independent KDBX implementation) so the
Rust reader is checked against files it did not produce itself. Seeds are random,
so regenerated files differ byte-wise; their decrypted content does not.
"""

import base64
import hashlib
import json
import os
import struct
import sys
from pathlib import Path

from pykeepass import create_database
from pykeepass.kdbx_parsing.kdbx4 import VariantDictionary, kdf_uuids

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "shared" / "test-vectors" / "kdbx4"

PASSWORD = "correct horse battery staple"
WRONG_PASSWORD = "Tr0ub4dor&3"
UNICODE_PASSWORD = "пароль-密码-🔑"
LEAK_MARKER = "VAZIE_KEEP_SECRET_DO_NOT_LEAK_42"

WEAK_ARGON2 = {"memory_kib": 1024, "iterations": 2, "parallelism": 2}
WEAK_AES_ROUNDS = 1000


def variant_dictionary(items):
    out = bytearray(b"\x00\x01")
    for key, (kind, value) in items.items():
        if kind == "u32":
            payload, tag = struct.pack("<I", value), 0x04
        elif kind == "u64":
            payload, tag = struct.pack("<Q", value), 0x05
        elif kind == "bytes":
            payload, tag = value, 0x42
        else:
            raise ValueError(kind)
        name = key.encode()
        out += bytes([tag]) + struct.pack("<I", len(name)) + name + struct.pack("<I", len(payload)) + payload
    out += b"\x00"
    return VariantDictionary.parse(bytes(out))


def kdf_parameters(kdf):
    salt = os.urandom(32)
    if kdf == "aes-kdf":
        return variant_dictionary({
            "$UUID": ("bytes", kdf_uuids["aeskdf"]),
            "R": ("u64", WEAK_AES_ROUNDS),
            "S": ("bytes", salt),
        })
    return variant_dictionary({
        "$UUID": ("bytes", kdf_uuids["argon2id" if kdf == "argon2id" else "argon2"]),
        "I": ("u64", WEAK_ARGON2["iterations"]),
        "M": ("u64", WEAK_ARGON2["memory_kib"] * 1024),
        "P": ("u32", WEAK_ARGON2["parallelism"]),
        "S": ("bytes", salt),
        "V": ("u32", 0x13),
    })


def populate_full(kp):
    kp.database_name = "Synthetic Test Vault"
    kp.database_description = "Generated by tooling/test-vectors/generate_kdbx4.py"
    root = kp.root_group
    web = kp.add_group(root, "Web")
    work = kp.add_group(web, "Work")
    deep = kp.add_group(work, "Deep Nesting Ünïcödé")
    kp.add_group(root, "Empty Group")

    kp.add_entry(root, "Root Entry", "root-user", "root-pass", url="https://example.com", notes="Line one\nLine two", force_creation=True)
    mail = kp.add_entry(web, "Example Mail", "alice@example.org", "hunter2-synthetic", url="https://mail.example.org/login", force_creation=True)
    mail.set_custom_property("Recovery Code", "RC-0000-1111", protect=True)
    mail.set_custom_property("Plain Note", "not secret", protect=False)
